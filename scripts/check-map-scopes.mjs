import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {loadLocalModule} from './load-map-model.mjs';

const app=new URL('../app/',import.meta.url);
const catalog=JSON.parse(await fs.readFile(new URL('catalog.json',app),'utf8'));
const scope=await loadLocalModule(new URL('scope-model.ts',app));
const byId=new Map(catalog.map(a=>[a.id,a]));
const doc={...scope.scopeDefaults,countryView:'',delhiView:'none',kashmirView:'separate',regions:Object.fromEntries(scope.scopeRegions.map(r=>[r.id,{show:r.id==='in-punjab',province:true,district:false,tehsil:true,uc:false,division:false}])),fills:{'in-d-608':{color:'#ff0000',pattern:'solid'}}};
const alphabetical=(a,b)=>a.localeCompare(b);
const ids=areas=>areas.map(a=>a.id).sort(alphabetical);
assert.deepEqual(scope.validateScopeSettings({}),scope.scopeDefaults,'old saved maps receive additive atlas defaults');
assert.deepEqual(scope.validateScopeSettings({mapScope:'invented',scopeRegion:'missing',scopeRegions:['in-delhi','missing','in-delhi'],historicRegions:[],fullDetail:'yes'}),{...scope.scopeDefaults,scopeRegions:['in-delhi'],historicRegions:[]});
const single={...doc,...scope.scopePreset(doc,'single',{scopeRegion:'in-delhi'})};
assert.equal(single.regions['in-delhi'].show,true);
assert.equal(single.regions['in-delhi'].district,false,'saved detail flags survive presets');
assert.equal(single.regions['in-punjab'].show,true,'nonselected region preferences are not destroyed');
assert.equal(single.fills,doc.fills,'paint object is preserved');
assert.equal(single.countryView,'');assert.equal(single.delhiView,'none');
assert.equal(scope.scopeAreaAllowed(byId.get('in-delhi'),single),true);
assert.equal(scope.scopeAreaAllowed(byId.get('in-punjab'),single),false);
assert.deepEqual(ids(scope.scopeGeometryAreas(single)),['in-delhi']);
assert.deepEqual(scope.scopeFocusBounds(single),byId.get('in-delhi').bbox);
const full={...doc,...scope.scopePreset(doc,'full')};
assert.equal(scope.scopeGeometryAreas(full).length,scope.scopeRegions.length-3,'coherent Pakistan avoids three legacy overlaps');
assert.equal(scope.scopeLevelAllowed(byId.get('in-d-608'),full),false,'full map does not automatically request all detail');
assert.equal(scope.scopeLevelAllowed(byId.get('in-d-608'),{...full,fullDetail:true}),true);
assert.equal(full.regions['in-punjab'].district,false);
const combo={...doc,...scope.scopePreset(doc,'combination',{scopeRegions:['in-delhi','in-punjab']})};
assert.deepEqual(ids(scope.scopeGeometryAreas(combo)),['in-delhi','in-punjab']);
assert.equal(scope.scopeAreaAllowed(byId.get('in-haryana'),combo),false);
const empty={...doc,...scope.scopePreset(doc,'combination',{scopeRegions:[]})};
assert.deepEqual(scope.scopeGeometryAreas(empty),[]);assert.equal(scope.scopeFocusBounds(empty),undefined);
const tricity={...doc,...scope.scopePreset(doc,'tricity')};
assert.deepEqual(ids(scope.scopeGeometryAreas(tricity)),[...scope.tricityAreaIds].sort(alphabetical));
for(const id of ['chandigarh','in-d-608','in-haryana-d-70','in-t-266','in-t-267','in-t-268','in-haryana-t-356','in-haryana-t-357','ch-ward-0'])assert.equal(scope.scopeAreaAllowed(byId.get(id),tricity),true,id+' is inside Tricity administrative context');
for(const id of ['in-punjab','in-haryana','in-d-27','in-haryana-d-62'])assert.equal(scope.scopeAreaAllowed(byId.get(id),tricity),false,id+' is outside Tricity administrative context');
assert.equal(scope.scopePrimaryArea(byId.get('in-d-608'),tricity),true);
assert.equal(scope.scopePrimaryArea(byId.get('in-t-267'),tricity),false);
assert.match(scope.scopeQualification(tricity),/not an exact urban/);
const historic={...doc,...scope.scopePreset(doc,'historic-punjab')};
assert.deepEqual(ids(scope.scopeGeometryAreas(historic)),[...scope.defaultHistoricRegions].sort(alphabetical));
assert.equal(scope.scopeRegionAllowed('pk-country',historic),false,'an enabled full-country Pakistan does not belong to custom Historic Punjab');
assert.match(scope.scopeQualification(historic),/not a surveyed historical/);
const edited={...historic,...scope.scopePreset(historic,'historic-punjab',{historicRegions:['in-punjab']})};
assert.deepEqual(ids(scope.scopeGeometryAreas(edited)),['in-punjab']);
assert.deepEqual(ids(scope.scopeGeometryAreas({...doc,delhiView:'ncr'})),['delhi-ncr']);
assert.deepEqual(ids(scope.scopeGeometryAreas({...doc,countryView:'np-nepal'})),['np-nepal']);
assert.deepEqual(ids(scope.scopeGeometryAreas({...doc,countryView:'tibet-modern-three'})),['tibet-modern-three']);
assert.equal(scope.scopeAreaAllowed(byId.get('kashmir-united'),single),false,'combined Kashmir cannot leak into a single-state map');
assert.equal(scope.scopeAreaAllowed(byId.get('tibet-modern-three'),single),false,'combined Tibetan context cannot leak into Delhi');
console.log(`Verified ${scope.scopeRegions.length} selectable regions, full/single/custom scope migration, detail preservation, Tricity hierarchy, Historic Punjab qualification and geographic source keys.`);
