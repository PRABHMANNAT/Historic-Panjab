import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read = p=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const data=read('app/gurdwara-data.json'),metadata=read('app/gurdwara-sources.json'),geo=read('public/data/gurdwaras.geojson');
assert.equal(data.length,100);
assert.deepEqual(Object.fromEntries(['takht','featured','historic'].map(tier=>[tier,data.filter(x=>x.tier===tier).length])),{takht:5,featured:15,historic:80});
assert.equal(new Set(data.map(x=>x.id)).size,100);
assert.equal(new Set(data.map(x=>x.sourceIdentity)).size,100);
assert.equal(new Set(data.map(x=>x.coordinates.join(','))).size,100);
assert.equal(data.find(x=>x.tier==='featured').id,'gs-harmandir-sahib');
assert.deepEqual(data.filter(x=>x.tier==='takht').map(x=>x.id),['gs-akal-takht','gs-keshgarh-takht','gs-patna-takht','gs-damdama-takht','gs-hazur-takht']);
for(const id of ['gs-harmandir-sahib','gs-fatehgarh-sahib','gs-jyoti-sarup-sahib'])assert.equal(data.find(x=>x.id===id)?.tier,'featured');
assert.ok(data.filter(x=>x.country==='Pakistan').length>=8);
assert.equal(geo.type,'FeatureCollection');assert.equal(geo.features.length,data.length+read('app/gurdwara-additions.json').length);
const evidenceById=new Map(metadata.coordinateEvidence.map(x=>[x.id,x]));
assert.equal(metadata.identityEvidence.length,100);
const identityById=new Map(metadata.identityEvidence.map(x=>[x.id,x]));
assert.equal(identityById.size,100);
for(const row of data){
 assert.ok(row.name&&row.city&&row.country&&row.coordinateAccuracy&&row.significanceSource&&row.sourceIdentity);
 for(const url of [row.sourceURL,row.significanceSource,row.coordinateSource])assert.ok(url.startsWith('https://'),`${row.id}: source URL must be HTTPS`);
 assert.equal(row.coordinates.length,2);assert.ok(row.coordinates.every(Number.isFinite));
 assert.ok(row.coordinates[0]>=67&&row.coordinates[0]<=90&&row.coordinates[1]>=17&&row.coordinates[1]<=35,`${row.id}: point outside curated region`);
 const evidence=evidenceById.get(row.id);assert.ok(evidence);
 assert.deepEqual(evidence.coordinates,row.coordinates);assert.equal(evidence.sourceIdentity,row.sourceIdentity);
 assert.equal(crypto.createHash('sha256').update(JSON.stringify(evidence.raw)).digest('hex'),evidence.rawSha256);
 const rawIdentity=evidence.sourceIdentity.startsWith('osm:')?`osm:${evidence.raw.type}/${evidence.raw.id}`:`wd:${evidence.raw.id}`;
 assert.equal(rawIdentity,row.sourceIdentity);
 assert.equal(evidence.sourceURL,row.coordinateSource);
 const published=evidence.sourceIdentity.startsWith('osm:')?(evidence.raw.center||evidence.raw):evidence.raw.claim.mainsnak.datavalue.value;
 assert.deepEqual(row.coordinates,evidence.sourceIdentity.startsWith('osm:')?[published.lon,published.lat]:[published.longitude,published.latitude]);
 const feature=geo.features.find(x=>x.id===row.id);assert.equal(feature.geometry.type,'Point');assert.deepEqual(feature.geometry.coordinates,row.coordinates);assert.deepEqual(feature.properties,row);
 assert.equal(row.sourceStatus,'verified-primary-reference',`${row.id}: primary source verification incomplete`);
 const identity=identityById.get(row.id);assert.ok(identity,`${row.id}: embedded named primary identity proof missing`);
 assert.equal(identity.sourceURL,row.significanceSource);assert.equal(identity.sourceURL,row.sourceURL);
 assert.equal(identity.namedIdentity,row.name);assert.equal(identity.locality,row.city);
 assert.equal(identity.significance,row.significance);
 assert.ok(identity.identityEvidence&&identity.sourceTitle&&identity.verificationMethod&&identity.accessedOn);
 const {id:identityId,recordSha256,...proof}=identity;
 assert.equal(identityId,row.id);
 assert.equal(crypto.createHash('sha256').update(JSON.stringify(proof)).digest('hex'),recordSha256);
}
assert.equal(crypto.createHash('sha256').update(fs.readFileSync(path.join(root,metadata.output.path))).digest('hex'),metadata.output.sha256);
assert.equal(crypto.createHash('sha256').update(fs.readFileSync(path.join(root,'app/gurdwara-data.json'))).digest('hex'),metadata.dataSha256);
assert.equal(metadata.databaseLicense,'ODbL-1.0');
console.log('Verified 100 unique named source-backed shrine points, all 5 Takhts, 15 editorial featured sites, embedded primary identity proofs, and source/output hashes.');
