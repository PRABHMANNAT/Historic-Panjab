  assert.equal((await saved()).kashmirView,'separate');
  await page.getByRole('button',{name:'Undo',exact:true}).click();
  assert.equal((await saved()).kashmirView,'combined','Mode participates in undo');
  await page.getByRole('button',{name:'Redo',exact:true}).click();
  assert.equal((await saved()).kashmirView,'separate','Mode participates in redo');
  await page.locator('input[type=file]').setInputFiles({name:'restored-map.json',mimeType:'application/json',buffer:settings});
  // File.text(), React state, and the auto-save effect complete asynchronously.
  await page.waitForFunction(()=>JSON.parse(localStorage.getItem('punjab-studio-regional-v2')).kashmirView==='combined');
