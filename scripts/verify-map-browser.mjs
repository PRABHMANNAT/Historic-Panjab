  assert.deepEqual(failures,[],'No HTTP errors');
  console.log(JSON.stringify({result:'passed',regions:6,boundaryResources:loaded.size,exports:['SVG','PNG'],saveReload:true,undoRedo:true,mobile:true,errors,failures},null,2));
